"""Build a git-filter-repo --replace-text expressions file from .env.

The file is written OUTSIDE any repository (default: a temp dir) and is deleted
by delete_expressions(). Secret values are read from .env and written without
being printed to stdout, stderr, or the terminal history.

Usage:
    python scripts/build_replace_text.py --out E:\\backups\\expressions.txt
    python scripts/build_replace_text.py --delete E:\\backups\\expressions.txt
"""
from __future__ import annotations

import argparse
import os
import sys
import tempfile
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parent.parent
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

SECRET_KEYS = ("MT5_PASSWORD", "OPENROUTER_API_KEY", "GROQ_API_KEY")

# Never write into a git working tree: the expressions file would itself be a
# new leak if it were ever staged.
FORBIDDEN_PARENTS = (".git",)


def load_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8-sig", errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def assert_outside_repo(out: Path) -> None:
    resolved = out.resolve()
    repo = _REPO_ROOT.resolve()
    try:
        resolved.relative_to(repo)
    except ValueError:
        return  # good: not inside the repo
    raise SystemExit(
        f"Refusing to write the expressions file inside the repository: {resolved}"
    )


def build(out: Path, env_path: Path) -> int:
    assert_outside_repo(out)
    values = load_env(env_path)

    lines = [
        "***REMOVED***",
        "# Generated by scripts/build_replace_text.py -- do not commit.",
        "# Format: <key>==>replacement",
        "# Only key names are echoed below; values are written to the file only.",
        "",
    ]
    written = 0
    for key in SECRET_KEYS:
        value = values.get(key, "")
        if not value or value.startswith("YOUR_"):
            continue
        lines.append(f"{key}:==>***REMOVED-{key}***")
        written += 1

    # filter-repo needs the literal value, not the key name, so write a second
    # block using the real values. These are never printed.
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
        fh.write("\n\n# literal replacements\n")
        for key in SECRET_KEYS:
            value = values.get(key, "")
            if not value or value.startswith("YOUR_"):
                continue
            fh.write(f"literal:{value}==>***REMOVED-{key}***\n")

    print(f"expressions file written: {out}")
    print(f"secrets included        : {written} (values not displayed)")
    print(f"file size               : {out.stat().st_size} bytes")
    print()
    print("This file contains your real secrets. Delete it after use:")
    print(f"    python scripts/build_replace_text.py --delete {out}")
    return 0


def delete(path: Path) -> int:
    if not path.exists():
        print(f"nothing to delete at {path}")
        return 0
    # Overwrite before unlinking so the bytes are not left recoverable in slack.
    try:
        size = path.stat().st_size
        with path.open("r+b") as fh:
            fh.write(b"\0" * size)
            fh.flush()
            os.fsync(fh.fileno())
    except OSError:
        pass
    path.unlink()
    print(f"deleted {path}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", help="path for the expressions file")
    parser.add_argument("--delete", help="path to delete (overwrite first)")
    parser.add_argument("--env", default=str(_REPO_ROOT / ".env"))
    args = parser.parse_args(argv)

    if args.delete:
        return delete(Path(args.delete))
    if not args.out:
        parser.error("--out is required unless --delete is used")

    out = Path(args.out)
    return build(out, Path(args.env))


if __name__ == "__main__":
    sys.exit(main())
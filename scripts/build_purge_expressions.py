"""Build a targeted filter-repo expressions file: ONLY the leaked credential.

The previous attempt matched any credential-SHAPED string in the source, which
collected hundreds of ordinary code tokens. Rewriting those would have mangled
the codebase. The only value that needs scrubbing is the one that was actually
committed: a real MT5 password used as scanner test data.

This finds it precisely:
  - it appears inside scripts/secret_scan.py or tests/test_secret_scan.py
  - it is assigned to a credential-named variable or parameter
  - it is NOT a declared canary (those are synthetic and must survive)

The value is read from the repository, never printed, and written only to a file
outside every repository.

Usage:
    python scripts/build_purge_expressions.py --repo <clone> --out <path>
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

# Files that can contain the leaked sample.
TARGET_FILES = ("scripts/secret_scan.py", "tests/test_secret_scan.py",
                "engine/keys.py", "config.yaml", "docs/V2_Implementation_Plan.md")

# Assignment to a credential-shaped name.
ASSIGNMENT = re.compile(
    r"""(?ix)
    \b (?: password | passwd | pwd | secret | api[_-]?key | apikey | token
          | live_key | real_key | key_value | orig_key | orig_password )
    \b
    \s* [:=]\s*
    [uUbBfFrR]? [\"'] (?P<val>[^\"']{6,}) [\"']
    """
)

# Synthetic canaries that must survive the purge: the scanner's own test data.
SYNTHETIC = re.compile(
    r"(AAAA|BBBB|CCCC|DDDD|EEEE|FFFF|gggg|xxxx|XXXX|EXAMPLE|YOUR_|CHANGEME|"
    r"REMOVED|REDACTED|synthetic|dummy|fake|stub|test-|notareal|unused)",
    re.IGNORECASE,
)

# Structural tokens that match the assignment shape but are not credentials.
STRUCTURAL = {
    "str", "None", "True", "False", "self", "value", "values", "payload",
    "provider", "token", "secret", "api_key", "password", "key", "name",
    "RiskApproval", "allowlist", "redacted", "removed",
}


def collect(repo: Path) -> dict[str, str]:
    """Credential literals in the target files, excluding known synthetic ones."""
    found: dict[str, str] = {}

    revs = subprocess.run(["git", "rev-list", "--all"], cwd=str(repo),
                          capture_output=True, text=True).stdout.split()

    for rev in revs:
        listing = subprocess.run(["git", "ls-tree", "-r", "--name-only", rev],
                                 cwd=str(repo), capture_output=True,
                                 text=True).stdout.split()
        for path in TARGET_FILES:
            if path not in listing:
                continue
            blob = subprocess.run(["git", "show", f"{rev}:{path}"],
                                  cwd=str(repo), capture_output=True).stdout
            if not blob:
                continue
            text = blob.decode("utf-8", "replace")
            for match in ASSIGNMENT.finditer(text):
                value = match.group("val")
                if value in STRUCTURAL or SYNTHETIC.search(value):
                    continue
                if len(value) < 6:
                    continue
                found[hashlib.sha256(value.encode()).hexdigest()[:12]] = value
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)

    repo = Path(args.repo)
    out = Path(args.out)

    if out.exists():
        print(f"refusing to overwrite {out}; delete it first")
        return 1

    secrets = collect(repo)
    print(f"real credential literals located: {len(secrets)}")
    print()
    if not secrets:
        print("  nothing to scrub")
        return 0

    lines = [
        "# git-filter-repo replacement expressions",
        "# Generated by scripts/build_purge_expressions.py",
        "# Contains literal leaked values. Delete after use. Never commit.",
        "",
    ]
    for fingerprint, value in sorted(secrets.items()):
        lines.append(f"literal:{value}==>***REDACTED-{fingerprint}***")
        print(f"  scrubbing sha256:{fingerprint}  len={len(value)}  "
              f"shape={value[:1]}***{value[-1:]}")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print()
    print(f"written to {out}  ({len(secrets)} replacement rule(s))")
    print("No secret value was printed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())